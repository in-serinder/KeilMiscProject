/* =====================================================================
 * board.c  —  上电初始化：端口模式、扩展寄存器访问、外设初值
 *
 * STC8 的端口四个模式（PxM1/PxM0）：
 *   00 准双向口  01 推挽输出  10 高阻输入  11 开漏输出
 * 复位值全是 00（准双向），所以只用显式改需要变的脚。
 * ===================================================================== */
#include "board.h"

void Board_Init(void)
{
    /* 允许访问 xdata 区的扩展 SFR（ADCTIM / 各端口 PxPU 等）。
     * 这一位置 1 只是"开窗"，不影响原有存储器，可以一直开着。 */
    P_SW2 |= 0x80;

    /* 蜂鸣器：推挽输出，先给低（不响）。
     * 有源蜂鸣器电流一般 20~30mA，8 脚 STC8G 单脚可直推，但建议串 100R 限流。 */
    P3M1 &= (uint8_t)~0x08;
    P3M0 |= 0x08;
    BEEP = 0;

    /* 数码管 CLK/DIO：准双向口。
     * 必须保持准双向（写 1 = 释放），键扫时才能把 DIO 读回来。 */
    P5M1 &= (uint8_t)~0x30;
    P5M0 &= (uint8_t)~0x30;
    TM1637_CLK = 1;
    TM1637_DIO = 1;

    /* MQ 模拟输入：高阻输入（ADC 采样必须是高阻，否则内部上拉会拉偏结果）。 */
    P3M1 |= 0x04;
    P3M0 &= (uint8_t)~0x04;

#if CFG_KEY_GPIO_MODE
    /* 按键直读：P3.0/P3.1 准双向 + 写 1，靠内部弱上拉，按下被 A(GND) 拉低 */
    P3M1 &= (uint8_t)~0x03;
    P3M0 &= (uint8_t)~0x03;
    KEY_ADD_PIN = 1;
    KEY_SUB_PIN = 1;
#endif
}
