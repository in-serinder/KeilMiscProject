/* board.c — 端口模式与上电默认状态 */
#include "board.h"
#include "delay.h"
#include "i2c_sw.h"

void Board_Init(void)
{
    /* P_SW2 的 bit7(EAXFR) 必须置 1 才能访问 xdata 映射的扩展 SFR
     * （I2CCFG / I2CMSCR / PxPU 等都在 0xFE00 段）*/
    P_SW2 |= 0x80;

    /* ---- 串口1：P3.0 / P3.1 准双向 ---- */
    P3M1 &= (uint8_t)~0x03;
    P3M0 &= (uint8_t)~0x03;

    /* ---- IIC1（硬件 I2C）：P3.2=SCL P3.3=SDA
     * 准双向 + 内部 4K 上拉：外部若已有 4.7K 上拉更稳；
     * 硬件 I2C 主机输出低电平由外设驱动，读回靠上拉，准双向即可。*/
    P3M1 &= (uint8_t)~0x0C;
    P3M0 &= (uint8_t)~0x0C;
    P3PU |= 0x0C;

    /* ---- IIC2（软件 I2C）：P5.4=SCL P5.5=SDA
     *
     * ★ 用**准双向**而不是开漏：
     *   开漏模式下"写 1"只是释放总线，必须依赖上拉电阻把线拉高。
     *   STC8 的内部上拉在 P5PU（xdata 映射的扩展 SFR）里，一旦 EAXFR 没开、
     *   或某颗片子该位不可用，写 1 就等于让引脚悬空 —— 总线永远上不去，
     *   表现就是"两条线一点动作都没有、整条 IIC2 上的器件全都不应答"。
     *   准双向（M1=0,M0=0）是 8051 的默认弱上拉输出，写 1 一定有高电平，
     *   写 0 是强下拉，配合模块上的 4.7K 上拉完全够用，也更接近示例工程
     *   （它把 P5 当普通 IO 驱动 TM1637 就是这么配的）。*/
    P5M1 &= (uint8_t)~0x30;
    P5M0 &= (uint8_t)~0x30;
    P5PU |= 0x30;                   /* 内部上拉作为额外余量，不依赖它 */
    SW_SCL = 1;
    SW_SDA = 1;

    /* ---- 其余未用引脚保持高阻输入，降低功耗 ---- */
    P1M1 = 0xFF;
    P1M0 = 0x00;
}

bit Board_SwI2cPinsOk(void)
{
    /* 实际测试交给 i2c_sw：它会针对**当前选中的引脚组**做推挽拉低读回，
     * 并保证测完先把锁存器置 1 再恢复模式（否则总线会被钉死在低电平）。*/
    return I2C2_PinsOk();
}
