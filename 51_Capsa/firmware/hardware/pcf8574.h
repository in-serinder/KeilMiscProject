#ifndef __PCF8574_H__
#define __PCF8574_H__

/* =====================================================================
 * pcf8574.h — 8 路 EEPROM 写保护控制器
 *
 * 总线：IIC2（软件 I2C，P5.4=SCL / P5.5=SDA），7 位地址 0x20（A2=A1=A0=0）
 *       与 24C02(0x51)、SSD1315(0x3C) 共用 IIC2，三者地址互不冲突。
 *       注意 PCF8574 **不在** IIC1：IIC1 只挂 8 片 24Cxx，是纯存储器总线。
 * 语义：输出位 1 = 对应 24Cxx 的 WP 拉高 = 开启写保护
 *       bit0~bit7 ↔ 0x50~0x57，与协议 SET 的 WP 掩码字段顺序一致
 *
 * 注：PCF8574 上电默认输出全高（所有片子写保护）。所以必须在初始化时
 *     主动写 0x00 解除保护，否则第一包 W_ 就会吃 [ERR_WP]。
 * ===================================================================== */

#include "board.h"

void    PCF_Init(void);
bit     PCF_Write(uint8_t mask);        /* 1 = 成功 */
bit     PCF_Read(uint8_t *mask);        /* 读回当前引脚电平 */
bit     PCF_SetMask(uint8_t mask);      /* 写 + 回读校验 + 5ms 等待 */

#endif /* __PCF8574_H__ */
