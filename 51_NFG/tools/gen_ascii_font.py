ORDER = [chr(c) for c in range(0x20, 0x7F)]
assert len(ORDER) == 95

data = []
for ch in ORDER:
    rows = G[ch].split()
    assert len(rows) == 7, ch
    cols = []
    for x in range(5):
        b = 0
        for y in range(7):
            if rows[y][x] == '#':
                b |= (1 << y)
        cols.append(b)
    data.append(cols)

# ---- 自检: 反解成字符画 ----
bad = 0
for idx, ch in enumerate(ORDER):
    rows = G[ch].split()
    back = []
