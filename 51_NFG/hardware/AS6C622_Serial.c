#include "AS6C622_Serial.h"
#include "SN74HC595N.h"
#include "SN74HC165N.h"

/* =========================================================================
 *  595-CTL 控制字约定 (见 SN74HC595N.h 的 CTL_BIT_xxx):
 *    CTL_BIT_RAM_OE   : 1 = RAM /OE 拉高(不驱动总线)  0 = RAM /OE 拉低(驱动总线)
 *    CTL_BIT_RAM_CE   : 1 = RAM /CE 拉高(未选中)      0 = RAM /CE 拉低(选中)
 *    CTL_BIT_DQ_OE    : 1 = 595-DQ 输出关闭(高阻)      0 = 595-DQ 驱动总线
 *    CTL_BIT_PL165    : 1 = 165 移位模式              0 = 165 装载
 *    CTL_BIT_A16_RCLR : 1 = 正常                     0 = 595-A16 清零
 *    CTL_BIT_DQ_RCLR  : 1 = 正常                     0 = 595-DQ  清零
 *
 *  常态控制字 (RCLR 保持正常、165 保持移位、总线空闲):
 * ========================================================================= */
#define CTL_BASE  (CTL_BIT_RAM_OE | CTL_BIT_RAM_CE | CTL_BIT_DQ_OE \
                                    | CTL_BIT_PL165  | CTL_BIT_A16_RCLR | CTL_BIT_DQ_RCLR)

/* =========================================================================
 *  初始化
 * ========================================================================= */
void AS6C622_Init(void)
{
  init_SN74HC595N();
  init_SN74HC165N();

  /* 先上电复位两组 595 寄存器, 再进入空闲 */
  SR595_A16_RCLR(0); SR595_A16_RCLR(1);
  SR595_DQ_RCLR(0);  SR595_DQ_RCLR(1);

  AS6C622_Idle();
}

/* 进入空闲: OE/CE 都拉高, 595-DQ 输出关闭 */
void AS6C622_Idle(void)
{
  SR595_CTL_Write(CTL_BASE);
}

void AS6C622_Select(void)
{
  SR595_RAM_CE(1);   /* enable 参数 1 -> CE 输出低 (选中) */
}

void AS6C622_Deselect(void)
{
  SR595_RAM_CE(0);   /* enable 参数 0 -> CE 输出高 (未选中) */
}

/* =========================================================================
 *  写一个字节
 *  1) 装入地址 (595-A16) 与数据 (595-DQ)
 *  2) 595-DQ 输出使能, RAM /OE 拉高, RAM /CE 拉高(准备)
 *  3) RAM /CE 拉低 -> 拉高  (上升沿锁存写入)
 *  4) 回到空闲
 * ========================================================================= */
void AS6C622_WriteByte(u16 addr, u8 dat)
{
  /* 控制字: RAM /OE=1, RAM /CE=1(未选中), 595-DQ 输出使能, 165 移位 */
  u8 wr_ctl = (u8)(CTL_BASE & (u8)~CTL_BIT_DQ_OE);

  /* 1. 地址与数据串行装入 */
  SR595_A16_Write(addr);
  SR595_DQ_Write(dat);

  /* 2. 使能 595-DQ 输出, 保持 RAM 未选中 */
  SR595_CTL_Write(wr_ctl);

    /* 3. RAM /CE 低脉冲: 选中 -> 释放, 上升沿写入 */
  SR595_RAM_CE(1);       /* CE = 0 (选中, 开始写) */
  _nop_(); _nop_(); _nop_(); _nop_();   /* 写脉宽 (对 22MHz 足够) */
  SR595_RAM_CE(0);       /* CE = 1 (释放, 数据被锁存) */

  /* 4. 空闲 */
  AS6C622_Idle();
}

/* =========================================================================
 *  读一个字节
 *  1) 装入地址 (595-A16) 与读地址回读(可选)
 *  2) 关闭 595-DQ 输出(高阻), RAM /OE 拉低, RAM /CE 拉低
 *  3) 用 165-DQ 采集总线
 *  4) 回到空闲
 *
 *  注意: 读完之后必须把 RAM /OE 拉回高、恢复 595-DQ 输出, 否则总线争用。
 * ========================================================================= */
u8 AS6C622_ReadByte(u16 addr)
{
  u8 dat;
  /* 控制字: RAM /OE=0(驱动), RAM /CE=0(选中), 595-DQ 输出关闭(高阻),
   *         165 移位, RCLR 正常 */
  u8 rd_ctl = (u8)(CTL_BASE
                   & (u8)~CTL_BIT_RAM_OE
                   & (u8)~CTL_BIT_RAM_CE);

  /* 1. 地址装入 (读操作也需要地址; 若读地址由 165 回读提供, 这里仍先写 595) */
  SR595_A16_Write(addr);

  /* 2. RAM 驱动总线, 595-DQ 让出总线 */
  SR595_CTL_Write(rd_ctl);

    /* 采样前给 RAM 一点建立时间 */
  _nop_(); _nop_(); _nop_(); _nop_();

  /* 3. 165 采集当前总线数据 */
  dat = SR165_DQ_Read();

  /* 4. 释放总线并回到空闲 */
  AS6C622_Idle();

  return dat;
}

/* =========================================================================
 *  连续写: 从 addr 开始, 顺序写入 len 个字节 (地址自增)
 * ========================================================================= */
void AS6C622_WriteBuffer(u16 addr, u8 *buf, u16 len)
{
  u16 i;
  for (i = 0; i < len; i++) {
    AS6C622_WriteByte((u16)(addr + i), buf[i]);
  }
}

/* =========================================================================
 *  连续读: 从 addr 开始, 顺序读入 len 个字节到 buf
 * ========================================================================= */
void AS6C622_ReadBuffer(u16 addr, u8 *buf, u16 len)
{
  u16 i;
  for (i = 0; i < len; i++) {
    buf[i] = AS6C622_ReadByte((u16)(addr + i));
  }
}
