#ifndef __SN74HC165N_H__
#define __SN74HC165N_H__
#include "stc90c58.h"

/* 基础类型 (自包含定义, 不改动 stc90c58.h) */
#ifndef TYPE_U8_U16_DEFINED
#define TYPE_U8_U16_DEFINED
typedef unsigned char  u8;
typedef unsigned int   u16;
#endif

// 多片SN74HC165N芯片

//共同控制并联了三片的CLK
#define CLK165 P20

// 控制AS6C622的DQ0-DQ7(映射165N的D0-D7) 的165控制引脚 这里命名芯片为165-DQ
#define DQ_CTL_OUT P21

//控制AS6C622的A0-A12(映射两片级联165N的A0-A7) 的165控制引脚 这里命名芯片为165-A12
// 末级165 控制引脚为A8-A12
#define AL_CTL_OUT P17
// 前级165 控制引脚为A0-A7
#define AR_CTL_SER P16

/* 165 芯片编号, 用于统一接口 */
#define SR165_DQ   0   /* 165-DQ   : DQ0-DQ7          (8 位)  */
#define SR165_A12  1   /* 165-A12  : A0-A12 (两片级联, 13 位) */

/* -------------------------------------------------------------------------
 *  初始化
 * ------------------------------------------------------------------------- */
void init_SN74HC165N(void);

/* -------------------------------------------------------------------------
 *  单个 165 芯片的位读取
 * ------------------------------------------------------------------------- */

/* 读取 165-DQ 的 8 位数据 (DQ0-DQ7) */
u8  SR165_DQ_Read(void);

/* 读取 165-A12 两片级联的 13 位地址 (A0-A12) */
u16 SR165_A12_Read(void);

/* 统一接口: chip 取 SR165_DQ/SR165_A12, 返回对应宽度数据 */
u16 SR165_Read(u8 chip);

/* -------------------------------------------------------------------------
 *  低层原语: 装载(并行读入) 与 逐位移位读
 *  一般用上面的高层函数即可; 需要手动控制时序时可用下面这些。
 * ------------------------------------------------------------------------- */

/* 165 的 PL 脉冲: 拉低装载并行数据, 再拉高进入移位模式。
 * 注意 PL 实际由 595-CTL 的 QD 控制, 所以调用前需保证 595 已初始化,
 * 这里直接通过 595 接口 SR595_PL165() 操作 (声明于 SN74HC595N.h)。 */
void SR165_Load(void);

/* 读一位: 读取当前 OUT 引脚电平后, 给 CLK 一个脉冲 */
u8  SR165_ShiftReadBit(void);

#endif
// __SN74HC165N_H__