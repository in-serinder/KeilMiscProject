#ifndef __AS6C622_SERIAL_H__
#define __AS6C622_SERIAL_H__

#include "stc90c58.h"

/* 基础类型 (自包含定义, 不改动 stc90c58.h) */
#ifndef TYPE_U8_U16_DEFINED
#define TYPE_U8_U16_DEFINED
typedef unsigned char  u8;
typedef unsigned int   u16;
#endif

/* =========================================================================
 *  AS6C62256 (32K x 8) 串行(595/165) 驱动
 *
 *  硬件通路:
 *    595-DQ  -> SRAM DQ0-DQ7     (写数据)
 *    595-A16 -> SRAM A0-A14      (写地址, 高 8 位用作 A8-A14)
 *    165-DQ  -> SRAM DQ0-DQ7     (读数据)
 *    165-A12 -> SRAM A0-A12      (读地址, 仅用于回读校验/地址无关读)
 *    595-CTL -> OE / CE / 各使能 / PL / RCLR
 *
 *  时序模型 (假定 SRAM 的 /WE 已硬件接地, 常态可写):
 *    写: 595-DQ 输出数据, 595-A16 输出地址, QC=1 使能 595-DQ 输出,
 *        RAM /OE=1(不驱动总线), 给 RAM /CE 一个 低脉冲 -> 上升沿锁存写入。
 *    读: QC=0 关闭 595-DQ 输出(高阻), RAM /OE=0 由 RAM 驱动总线,
 *        RAM /CE=0, 用 165-DQ 采集当前总线数据。
 * ========================================================================= */

/* 芯片容量常量 */
#define AS6C622_SIZE   0x8000U   /* 32K 字节 */
#define AS6C622_LAST   0x7FFFU

/* -------------------------------------------------------------------------
 *  初始化: 初始化 595/165, 并把 RAM 置于空闲(不被选中)状态
 * ------------------------------------------------------------------------- */
void AS6C622_Init(void);

/* -------------------------------------------------------------------------
 *  基本总线操作 (每次操作即完整走一遍串行时序)
 * ------------------------------------------------------------------------- */

/* 写一个字节到指定地址 */
void AS6C622_WriteByte(u16 addr, u8 dat);

/* 从指定地址读一个字节 (通过 165 回读总线) */
u8   AS6C622_ReadByte(u16 addr);

/* -------------------------------------------------------------------------
 *  连续读写 (地址自增, 一次调用读/写一整块)
 * ------------------------------------------------------------------------- */
void AS6C622_WriteBuffer(u16 addr, u8 *buf, u16 len);
void AS6C622_ReadBuffer(u16 addr, u8 *buf, u16 len);

/* -------------------------------------------------------------------------
 *  RAM 片选/使能 高层控制
 * ------------------------------------------------------------------------- */
void AS6C622_Select(void);     /* CE 使能 (低) */
void AS6C622_Deselect(void);   /* CE 禁止 (高) */
void AS6C622_Idle(void);       /* 进入安全空闲: OE/CE 都拉高, 595-DQ 输出关 */

#endif
// __AS6C622_SERIAL_H__
