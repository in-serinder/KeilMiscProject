/*============================================================================
  GPIO 初始化
============================================================================*/
void LCD_GPIO_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStructure;

    /* 使能 GPIOA、GPIOB 时钟 */
    RCC_APB2PeriphClockCmd(RCC_APB2Periph_GPIOA | RCC_APB2Periph_GPIOB, ENABLE);

    /* LCD 引脚：推挽输出 */
    GPIO_InitStructure.GPIO_Mode  = GPIO_Mode_Out_PP;
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_InitStructure.GPIO_Pin   = LCD_SCLK_PIN | LCD_SID_PIN | LCD_RS_PIN |
                                    LCD_RESET_PIN | LCD_CS1_PIN;
    GPIO_Init(LCD_SCLK_PORT, &GPIO_InitStructure);

    /* 字库IC输出引脚：推挽输出 */
    GPIO_InitStructure.GPIO_Pin = ROM_IN_PIN | ROM_SCK_PIN | ROM_CS_PIN;
    GPIO_Init(ROM_IN_PORT, &GPIO_InitStructure);

    /* 字库IC数据输出引脚（ROM_OUT）：浮空输入 */
    GPIO_InitStructure.GPIO_Mode = GPIO_Mode_IN_FLOATING;
    GPIO_InitStructure.GPIO_Pin  = ROM_OUT_PIN;
    GPIO_Init(ROM_OUT_PORT, &GPIO_InitStructure);

    /* 初始电平：CS1=1, CS=1, SCLK=0 */
    LCD_CS1_H();
    ROM_CS_H();
    LCD_SCLK_L();
    ROM_SCK_L();
}

/*============================================================================
  写指令到 LCD 模块（软件 SPI，MSB first）
  注：原 8051 代码中 transfer_command_lcd 的 for 循环体为空，属排版错误，
      此处参照 transfer_data_lcd 的正确实现修正。
============================================================================*/
void Transfer_Command_LCD(uchar data1)
{
    char i;
    LCD_CS1_L();          /* 片选有效 */
    LCD_RS_L();           /* RS=0：指令 */
    for(i = 0; i < 8; i++)
    {
        LCD_SCLK_L();
        if(data1 & 0x80) LCD_SID_H();
        else             LCD_SID_L();
        LCD_SCLK_H();     /* 上升沿采样 */
        data1 <<= 1;
    }
    LCD_CS1_H();          /* 片选无效 */
}

/*============================================================================
  写数据到 LCD 模块
============================================================================*/
void Transfer_Data_LCD(uchar data1)
{
    char i;
    LCD_CS1_L();
    LCD_RS_H();           /* RS=1：数据 */
    for(i = 0; i < 8; i++)
    {
        LCD_SCLK_L();
        if(data1 & 0x80) LCD_SID_H();
        else             LCD_SID_L();
        LCD_SCLK_H();
        data1 <<= 1;
    }
    LCD_CS1_H();
}

/*============================================================================
  LCD 模块初始化（UC1701X / ST7565R 兼容）
============================================================================*/
void LCD_Init(void)
{
    LCD_GPIO_Init();

    LCD_RESET_L();        /* 低电平复位 */
    Delay_ms(100);
    LCD_RESET_H();        /* 复位完毕 */
    Delay_ms(100);

    Transfer_Command_LCD(0xE2);  /* 软复位 */
    Delay_ms(5);
    Transfer_Command_LCD(0x2C);  /* 升压步骤 1 */
    Delay_ms(50);
    Transfer_Command_LCD(0x2E);  /* 升压步骤 2 */
    Delay_ms(50);
    Transfer_Command_LCD(0x2F);  /* 升压步骤 3 */
    Delay_ms(5);
    Transfer_Command_LCD(0x23);  /* 粗调对比度 0x20~0x27 */
    Transfer_Command_LCD(0x81);  /* 微调对比度 */
    Transfer_Command_LCD(0x28);  /* 微调对比度值 0x00~0x3F */
    Transfer_Command_LCD(0xA2);  /* 1/9 偏压比 (bias) */
    Transfer_Command_LCD(0xC8);  /* 行扫描顺序：从上到下 */
    Transfer_Command_LCD(0xA0);  /* 列扫描顺序：从左到右 */
    Transfer_Command_LCD(0x40);  /* 起始行：第一行开始 */
    Transfer_Command_LCD(0xAF);  /* 开显示 */
}

/*============================================================================
  设置 LCD 页地址和列地址
  page: 1~8（每8行为一页，64行共8页）
  column: 1~128
============================================================================*/
void LCD_Address(uint page, uint column)
{
    column = column - 0x01;
    Transfer_Command_LCD(0xB0 + page - 1);                  /* 设置页地址 */
    Transfer_Command_LCD(0x10 + ((column >> 4) & 0x0F));    /* 列地址高4位 */
    Transfer_Command_LCD(column & 0x0F);                    /* 列地址低4位 */
}

/*============================================================================
  全屏清屏
============================================================================*/
void LCD_Clear(void)
{
    unsigned char i, j;
    for(i = 0; i < 8; i++)
    {
        Transfer_Command_LCD(0xB0 + i);
        Transfer_Command_LCD(0x10);
        Transfer_Command_LCD(0x00);
        for(j = 0; j < 132; j++)
        {
            Transfer_Data_LCD(0x00);
        }
    }
}

/*============================================================================
  显示 128x64 点阵图像
============================================================================*/
void Display_128x64(const uchar *dp)
{
    uint i, j;
    for(j = 0; j < 8; j++)
    {
        LCD_Address(j + 1, 1);
        for(i = 0; i < 128; i++)
        {
            Transfer_Data_LCD(*dp);
            dp++;
        }
    }
}

