/*============================================================================
  送指令到晶联讯字库 IC（JLX-GB2312）
============================================================================*/
void Send_Command_To_ROM(uchar datu)
{
    uchar i;
    for(i = 0; i < 8; i++)
    {
        ROM_SCK_L();
        Delay_us(10);
        if(datu & 0x80) ROM_IN_H();
        else            ROM_IN_L();
        datu <<= 1;
        ROM_SCK_H();
        Delay_us(10);
    }
}

/*============================================================================
  从晶联讯字库 IC 中读取 1 个字节数据
============================================================================*/
uchar Get_Data_From_ROM(void)
{
    uchar i;
    uchar ret_data = 0;
    for(i = 0; i < 8; i++)
    {
        ROM_SCK_L();
        ret_data <<= 1;
        if(ROM_OUT_READ())
            ret_data |= 1;
        ROM_SCK_H();
    }
    return ret_data;
}

/*============================================================================
  从指定地址读出 16x16 点阵数据写到液晶屏指定坐标
============================================================================*/
void Get_And_Write_16x16(ulong fontaddr, uchar page, uchar column)
{
    uchar i, j, disp_data;
    ROM_CS_L();
    Send_Command_To_ROM(0x03);                              /* 读命令 */
    Send_Command_To_ROM((fontaddr & 0xFF0000) >> 16);       /* 地址高8位 */
    Send_Command_To_ROM((fontaddr & 0xFF00) >> 8);          /* 地址中8位 */
    Send_Command_To_ROM(fontaddr & 0xFF);                   /* 地址低8位 */
    for(j = 0; j < 2; j++)
    {
        LCD_Address(page + j, column);
        for(i = 0; i < 16; i++)
        {
            disp_data = Get_Data_From_ROM();
            Transfer_Data_LCD(disp_data);
        }
    }
    ROM_CS_H();
}

